export const LANGS = ['en', 'zh-Hant'];
let current = 'en';

export function systemLang() {
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  for (const l of langs) {
    const lower = l.toLowerCase();
    if (lower.startsWith('zh')) return 'zh-Hant';
    if (lower.startsWith('en')) return 'en';
  }
  return 'en';
}

export function resolveLang(pref) {
  return LANGS.includes(pref) ? pref : systemLang();
}

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'en';
  document.documentElement.lang = current === 'en' ? 'en' : 'zh-Hant';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll('[data-i18n-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
    el.title = t(el.dataset.i18nLabel);
  }
}

export const getLang = () => current;

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}
